"""Shared bits for the silent format prototypes (proto/D quiz, proto/E map, proto/F ranking).

Each prototype is a standalone HyperFrames project generated by proto/<X>/build.py:
    index.html (root: scene hosts + master timeline with the stamped seams) + compositions/*.html + assets/ (gitignored)
Media come from Wikimedia Commons (free licences only) via fetch() below and land in proto/media/ (gitignored).
Render (silent, no audio track):  python3 proto/render.py D   → proto/D/renders/D.mp4
"""
import json, os, re, subprocess, time, urllib.request, urllib.parse

ROOT = os.path.dirname(os.path.abspath(__file__))
MEDIA = os.path.join(ROOT, 'media')
UA = {"User-Agent": "WikiRoulette-PhotoFetcher/1.0 (https://github.com/Mehrdadeshghi/YT)"}
W, H = 1080, 1920
J = json.dumps
SKILLS = os.path.expanduser('~/.claude/skills/motion-doctrine/scripts')


def fetch(name, title, width=2400):
    """Commons file → proto/media/<name>.<ext> + <name>.credit.json (licence, author, page). width 0 = original."""
    os.makedirs(MEDIA, exist_ok=True)
    have = [f for f in os.listdir(MEDIA) if f.startswith(name + '.') and not f.endswith('.json')]
    if have: return os.path.join(MEDIA, have[0])
    p = dict(action="query", format="json", titles=title, redirects=1, prop="imageinfo", iiprop="url|size|extmetadata|mime",
             **({"iiurlwidth": width} if width else {}))
    d = json.load(urllib.request.urlopen(urllib.request.Request("https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(p), headers=UA)))
    pg = list(d['query']['pages'].values())[0]; ii = pg['imageinfo'][0]; m = ii['extmetadata']
    url = ii['url'] if not width else (ii.get('thumburl') or ii['url'])
    ext = os.path.splitext(urllib.parse.urlparse(url).path)[1].lower() or '.jpg'
    dst = os.path.join(MEDIA, name + ext)
    open(dst, 'wb').write(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=300).read())
    clean = lambda s: re.sub('<[^>]+>', '', s or '').strip()
    json.dump(dict(title=pg['title'], url=ii['descriptionurl'], license=clean(m.get('LicenseShortName', {}).get('value')),
                   artist=clean(m.get('Artist', {}).get('value'))[:200]), open(os.path.join(MEDIA, name + '.credit.json'), 'w'), indent=1)
    time.sleep(1.5)
    return dst


def credits(names):
    out = []
    for n in names:
        p = os.path.join(MEDIA, n + '.credit.json')
        if os.path.exists(p):
            c = json.load(open(p)); out.append(f"- {c['title'][5:]} — {c['artist'] or 'unknown'}, {c['license']} ({c['url']})")
    return '\n'.join(out)


