def index(title, dur, hosts, bg='#06080C', master_js=''):
    """hosts: [(id, start, dur, z)] — each mounts compositions/<id>.html; the master timeline carries the seams (stamped from ledger.json)"""
    hs = '\n'.join(f'''      <div id="{h}" data-composition-id="{h}" data-composition-src="compositions/{h}.html" data-start="{s:.3f}" data-duration="{d:.3f}"
        data-track-index="{i + 1}" data-track-kind="graphics" data-width="{W}" data-height="{H}" style="position:absolute; inset:0; z-index:{z}"></div>'''
                   for i, (h, s, d, z) in enumerate(hosts))
    return f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <title>{title}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: {W}px; height: {H}px; overflow: hidden; background: {bg}; }}
      #main {{ position: relative; width: {W}px; height: {H}px; overflow: hidden; background: {bg}; }}
    </style>
  </head>
  <body>
    <div id="main" data-composition-id="main" data-start="0" data-duration="{dur:.2f}" data-width="{W}" data-height="{H}" data-fps="30">
{hs}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["main"] = tl;
{master_js}
      tl.set({{}}, {{}}, {dur:.2f});
    </script>
  </body>
</html>
"""


def write_project(d, files, ledger=None):
    os.makedirs(os.path.join(d, 'compositions'), exist_ok=True)
    for name, txt in files.items():
        open(os.path.join(d, name), 'w').write(txt)
    if not os.path.exists(os.path.join(d, 'hyperframes.json')):
        json.dump({'name': os.path.basename(d)}, open(os.path.join(d, 'hyperframes.json'), 'w'))
    if ledger:
        json.dump(ledger, open(os.path.join(d, 'ledger.json'), 'w'), indent=1)
        subprocess.run(['node', os.path.join(SKILLS, 'seam-stamp.mjs'), '--ledger', os.path.join(d, 'ledger.json'),
                        '--write', os.path.join(d, 'index.html')], check=True)
