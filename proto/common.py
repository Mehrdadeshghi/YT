EASE_JS = r"""
      const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
      const EZ = {
        lin: (u) => u,
        io2: (u) => u < 0.5 ? 2 * u * u : 1 - Math.pow(-2 * u + 2, 2) / 2,
        io3: (u) => u < 0.5 ? 4 * u * u * u : 1 - Math.pow(-2 * u + 2, 3) / 2,
        o3: (u) => 1 - Math.pow(1 - u, 3), o4: (u) => 1 - Math.pow(1 - u, 4), i3: (u) => u * u * u, i4: (u) => u * u * u * u,
        oexpo: (u) => u >= 1 ? 1 : 1 - Math.pow(2, -10 * u),
      };
      // keyframed value: K = [{t, v..., e}] — each key eases FROM the previous key over [prev.t, key.t]
      function kf(K, t, prop) {
        if (t <= K[0].t) return K[0][prop];
        for (let i = 1; i < K.length; i++) {
          const a = K[i - 1], b = K[i];
          if (t <= b.t) { const u = EZ[b.e || 'io3']((t - a.t) / Math.max(1e-6, b.t - a.t)); return a[prop] + (b[prop] - a[prop]) * u; }
        }
        return K[K.length - 1][prop];
      }
      // camera over a big image: source point (cx, cy) lands on frame point (fx, fy) at scale s; zoom interpolated in log space
      function camAt(K, t) {
        const ls = (k) => Math.log(k.s);
        if (t <= K[0].t) return K[0];
        for (let i = 1; i < K.length; i++) {
          const a = K[i - 1], b = K[i];
          if (t <= b.t) {
            const u = EZ[b.e || 'io3']((t - a.t) / Math.max(1e-6, b.t - a.t)), L = (p) => a[p] + (b[p] - a[p]) * u;
            return { cx: L('cx'), cy: L('cy'), fx: L('fx'), fy: L('fy'), s: Math.exp(ls(a) + (ls(b) - ls(a)) * u) };
          }
        }
        return K[K.length - 1];
      }
      function applyCam(el, c) {
        el.style.transform = `translate(${(c.fx - c.cx * c.s).toFixed(2)}px, ${(c.fy - c.cy * c.s).toFixed(2)}px) scale(${c.s.toFixed(5)})`;
      }
      const toFrame = (c, x, y) => [c.fx + (x - c.cx) * c.s, c.fy + (y - c.cy) * c.s];
"""

