def ep(n, series, title, hook, opening, rows, cta_seg, cta, spell, source, photos, music):
    sc = []
    for i, (en, cap, de, es, fr) in enumerate(rows):
        sc.append({'dur': 1.6, 'vis': i, 'vo': [{'at': 0.45, 'text': en, 'cap': cap, 'de': de, 'es': es, 'fr': fr}]})
    en, de, es, fr = cta_seg
    sc[-1]['vo'].append({'at': '0.15', 'text': en, 'cta': True, 'de': de, 'es': es, 'fr': fr})
    en, de, es, fr = opening
    E = dict(BASE, ep=n, series=series, prog=1, title=title, hook=hook, spell=spell, cta=cta, source=source,
             vo_open=[{'at': 0, 'text': en, 'de': de, 'es': es, 'fr': fr}], scenes=sc,
             photos=[{'id': k, 'file': f'File:{v}'} for k, v in photos] + [dict({'id': 'music', 'audio': f'File:{music[0]}'}, **music[1])])
    json.dump(E, open(f'episodes/{n}.json', 'w'), ensure_ascii=False, indent=1)
    print(n, len(sc), 'scenes', sum(len(v['text'].split()) for s in sc for v in s['vo']) + len(opening[0].split()), 'words')

